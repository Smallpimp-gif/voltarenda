// Генерация договора аренды (.docx) по шаблону №17 (Завьялов). Реквизиты
// Арендодателя фиксированы; данные Арендатора — из заявки. Условия аренды:
// 5500 ₽/нед × 41 неделя (итого 225 500 ₽), велосипед U2 Pro + 2×60/33.
//
// Работает в Node и в Cloudflare Workers: docx — чистый JS, на выходе Blob.

import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  AlignmentType,
} from "docx";

export type ContractTenant = {
  fio: string;
  birthDate?: string;
  birthPlace?: string;
  passportSeries?: string;
  passportNumber?: string;
  issuedBy?: string;
  issueDate?: string;
  departmentCode?: string;
  regAddress?: string;
  factAddress?: string;
  phone?: string;
  telegram?: string;
};

export type ContractData = {
  number: number;
  dateText: string; // напр. «27 июня 2026 г.»
  tenant: ContractTenant;
};

const WEEKLY = 5500;
const WEEKS = 41;
const TOTAL = WEEKLY * WEEKS; // 225 500

function p(text: string, opts: { bold?: boolean; center?: boolean; size?: number } = {}) {
  return new Paragraph({
    alignment: opts.center ? AlignmentType.CENTER : AlignmentType.JUSTIFIED,
    spacing: { after: 120 },
    children: [new TextRun({ text, bold: opts.bold, size: opts.size ?? 22 })],
  });
}

function heading(text: string) {
  return new Paragraph({
    spacing: { before: 160, after: 100 },
    children: [new TextRun({ text, bold: true, size: 22 })],
  });
}

function tenantLine(t: ContractTenant): string {
  const parts: string[] = [t.fio];
  if (t.birthDate) parts.push(`${t.birthDate} г.р.`);
  if (t.birthPlace) parts.push(`место рождения: ${t.birthPlace}`);
  const sn = [t.passportSeries, t.passportNumber].filter(Boolean).join(" № ");
  if (sn) parts.push(`паспорт ${sn}`);
  if (t.issuedBy || t.issueDate)
    parts.push(`выдан ${[t.issueDate, t.issuedBy].filter(Boolean).join(" ")}`.trim());
  if (t.departmentCode) parts.push(`код подразделения ${t.departmentCode}`);
  if (t.regAddress) parts.push(`адрес рег.: ${t.regAddress}`);
  if (t.factAddress) parts.push(`адрес факт.: ${t.factAddress}`);
  if (t.phone) parts.push(`тел. ${t.phone}`);
  if (t.telegram) parts.push(`Telegram: @${t.telegram.replace(/^@/, "")}`);
  return parts.join(", ") + " — именуемый «Арендатор», совместно «Стороны».";
}

