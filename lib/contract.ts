export type ContractKind = "аренда" | "выкуп";

export type ContractData = {
  number: number;
  dateText: string; // напр. «27» июня 2026 г.
  kind: ContractKind;
  tenant: ContractTenant;
};

const WEEKLY = 5500;
const BUYOUT_WEEKS = 41;
